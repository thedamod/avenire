export interface CaptureOutput {
  readonly tabs: readonly CapturedTab[];
  readonly pages: readonly PageSnapshot[];
  readonly files: readonly CapturedFile[];
  readonly skipped: readonly { readonly tabId: number; readonly reason: string }[];
}

const emptyPage = (tab: CapturedTab): PageSnapshot => ({
  tabId: tab.tabId,
  url: tab.finalUrl ?? tab.url,
  title: tab.title,
  description: "",
  language: "",
  text: "",
  textLength: 0,
  truncated: false,
  signals: { visibleTextLength: 0, paywallContainers: [], passwordInput: false },
});

export function safePage(page: PageSnapshot): PageSnapshot {
  return {
    ...page,
    url: normalizeUrl(page.url),
    ...(page.canonicalUrl ? { canonicalUrl: normalizeUrl(page.canonicalUrl) } : {}),
    ...(page.download
      ? {
          download: {
            ...page.download,
            url: normalizeUrl(page.download.url),
            ...(page.download.originUrl
              ? { originUrl: normalizeUrl(page.download.originUrl) }
              : {}),
          },
        }
      : {}),
    ...(page.file
      ? {
          file: {
            ...page.file,
            url: normalizeUrl(page.file.url),
            ...(page.file.originUrl ? { originUrl: normalizeUrl(page.file.originUrl) } : {}),
          },
        }
      : {}),
  };
}

// Browser/network errors can include private file paths or signed URLs. Only fixed reasons
// generated by this reader may leave the extension.
const readFailureReason = (error: unknown): string => {
  const message = error instanceof Error ? error.message : "";
  return /^(?:Capture file limit exceeded|Document redirect blocked by capture policy|Document request failed \(\d+\)|Document returned a login or HTML page|Document response has no body|Document is empty|Unsupported document type|Open Avenire desktop to capture files from this computer|Page content unavailable|Page no longer permitted|Discovered-link limit reached \(10 per tab\))$/.test(
    message,
  )
    ? message
    : /^(?:Browser download (?:interrupted: [A-Z_]+|timed out|was saved outside Avenire))$/.test(
          message,
        )
      ? message
      : "Document could not be read in this browser session";
};

export async function captureTabs(
  api: typeof chrome,
  input: readonly CapturedTab[],
  readInBrowser: boolean,
  options: {
    readonly tabTimeoutMs?: number;
    readonly totalTimeoutMs?: number;
    readonly fetcher?: typeof fetch;
    /** Desktop reads local files itself and records their private paths. */
    readonly desktop?: boolean;
    readonly captureId?: string;
    readonly reusableDownloads?: readonly string[];
    /** Browser-observed navigation time for protected viewers that reject script injection. */
    readonly pageOpenedAt?: (tabId: number) => number | undefined;
    /** Called once per completed tab; lets both transports consume and release originals early. */
    readonly onTab?: (output: CaptureOutput) => Promise<void>;
    readonly retainFiles?: boolean;
  } = {},
): Promise<CaptureOutput> {
  const tabs = permittedTabs(input).sort(
    (a, b) =>
      Number(b.activeInWindow) - Number(a.activeInWindow) ||
      Number(isEngaged(b)) - Number(isEngaged(a)),
  );
  if (
    !readInBrowser &&
    (options.desktop || !tabs.some((tab) => /^file:/i.test(tab.finalUrl ?? tab.url)))
  )
    return { tabs: tabs.map(publicTab), pages: [], files: [], skipped: [] };
  const restoreDownloads = options.desktop ? await hideCaptureDownloads(api) : undefined;
  const captureId = options.captureId ?? crypto.randomUUID();
  const deadline = Date.now() + (options.totalTimeoutMs ?? 20_000);
  const pages: PageSnapshot[] = [];
  const files: CapturedFile[] = [];
  const skipped: { tabId: number; reason: string }[] = [];
  const updated = new Map(tabs.map((tab) => [tab.tabId, tab]));
  const total = { bytes: 0 };
  const deliveries: Promise<void>[] = [];
  const deliveryErrors: unknown[] = [];
  const deliver = (output: CaptureOutput) => {
    if (options.onTab)
      deliveries.push(
        Promise.resolve()
          .then(() => options.onTab!(output))
          .catch((error) => {
            deliveryErrors.push(error);
          }),
      );
  };
  let next = 0;
  const worker = async () => {
    while (next < tabs.length) {
      const tab = tabs[next++]!;
      const tabPages: PageSnapshot[] = [];
      const tabFiles: CapturedFile[] = [];
      const tabSkipped: { tabId: number; reason: string }[] = [];
      const budget: FileBudget = {
        count: 0,
        urls: new Set(),
        get bytes() {
          return total.bytes;
        },
        set bytes(value: number) {
          total.bytes = value;
        },
      };
      let messageBytes = 1024;
      const accept = (page: PageSnapshot, file?: CapturedFile) => {
        let clean = safePage(page);
        const measure = (value: PageSnapshot): number =>
          new TextEncoder().encode(JSON.stringify(value)).byteLength + 2;
        let size = measure(clean);
        const available = MAX_MESSAGE_BYTES - 128_000 - messageBytes;
        if (size > available && !file) {
          // Fit visible text to the JSON byte budget, including UTF-8 and JSON escaping.
          let low = 0,
            high = clean.text.length;
          while (low < high) {
            const middle = Math.ceil((low + high) / 2);
            if (
              measure({
                ...clean,
                text: clean.text.slice(0, middle),
                textLength: middle,
                truncated: true,
              }) <= available
            )
              low = middle;
            else high = middle - 1;
          }
          let text = clean.text.slice(0, low);
          if (/[\uD800-\uDBFF]$/.test(text)) text = text.slice(0, -1);
          clean = { ...clean, text, textLength: text.length, truncated: true };
          size = measure(clean);
        }
        if (tabPages.length >= 200 || messageBytes + size > MAX_MESSAGE_BYTES - 128_000) {
          tabSkipped.push({ tabId: page.tabId, reason: "Capture response size limit reached" });
          return;
        }
        messageBytes += size;
        tabPages.push(clean);
        if (file) tabFiles.push({ ...file, page: clean });
      };
      // Share the remaining total deadline across queued waves so a hung first wave cannot
      // prevent later tabs from being attempted. Six seconds remains the per-tab ceiling.
      const waves = Math.max(1, Math.ceil((tabs.length - next + 1) / 6));
      const remaining = Math.min(
        options.tabTimeoutMs ?? 6000,
        Math.floor((deadline - Date.now()) / waves),
      );
      if (remaining <= 0) {
        tabSkipped.push({ tabId: tab.tabId, reason: "Read in browser timed out" });
        skipped.push(...tabSkipped);
        deliver({
          tabs: [publicTab(updated.get(tab.tabId)!)],
          pages: [],
          files: [],
          skipped: tabSkipped,
        });
        continue;
      }
      const controller = new AbortController();
      const tabDeadline = Date.now() + remaining;
      const timer = setTimeout(() => controller.abort(), remaining);
      const read = async () => {
        const local = (tab.finalUrl ?? tab.url).startsWith("file:");
        if ((!local && !readInBrowser) || (local && options.desktop)) return;
        if (local && !(await api.extension.isAllowedFileSchemeAccess()))
          throw new Error("Open Avenire desktop to capture files from this computer");
        let pageSince = options.pageOpenedAt?.(tab.tabId) ?? Date.now();
        if (options.desktop) {
          try {
            const times = await within(
              api.scripting.executeScript({
                target: { tabId: tab.tabId },
                func: () => performance.timeOrigin,
              }),
              Math.min(200, remaining),
            );
            const value = times[0]?.result;
            if (typeof value === "number" && Number.isFinite(value) && value > 0) pageSince = value;
          } catch {
            /* Restricted PDF viewers can only reuse a copy from this capture. */
          }
        }
        const knownDocument = resolveDocumentUrl(tab.finalUrl ?? tab.url);
        let page = emptyPage(tab);
        if (!knownDocument) {
          // Document viewers and canvas editors can leave executeScript pending indefinitely.
          // Their original can be read directly through the credentialed service-worker fetch.
          try {
            const extracted = await api.scripting.executeScript({
              target: { tabId: tab.tabId },
              func: extractPage,
              args: [tab.tabId],
            });
            page = Schema.decodeUnknownSync(PageSnapshot)(extracted[0]?.result);
          } catch {
            throw new Error("Page content unavailable");
          }
        }
        if (controller.signal.aborted) return;
        const current: CapturedTab = {
          ...tab,
          url: page.url,
          finalUrl: page.url,
          title: page.title,
        };
        if (!permittedTabs([current]).length || page.tabId !== tab.tabId)
          throw new Error("Page no longer permitted");
        const access = classifyAccess(page.signals);
        const summary = (page.abstract || page.description).slice(0, 10000);
        updated.set(tab.tabId, {
          ...tab,
          finalUrl: page.url,
          access,
          summary,
          ...(access === "open" ? {} : { selection: undefined, position: undefined }),
        });
        if (access !== "open") {
          // Only the tab's typed access and abstract leave the browser; no blocked text or files.
          tabSkipped.push({ tabId: tab.tabId, reason: access });
          return;
        }
        if (page.text.trim()) accept(page);
        const captureDocument = async (hint: DocumentHint): Promise<boolean> => {
          if (controller.signal.aborted) return false;
          if (
            !permittedTabs([{ ...current, url: hint.url, finalUrl: hint.url }]).length ||
            (hint.originUrl &&
              !permittedTabs([{ ...current, url: hint.originUrl, finalUrl: hint.originUrl }])
                .length)
          )
            return false;
          try {
            if (/^file:/i.test(hint.url)) {
              if (options.desktop) return false;
              if (!(await api.extension.isAllowedFileSchemeAccess()))
                throw new Error("Open Avenire desktop to capture files from this computer");
            }
            if (options.desktop && /^https?:/i.test(hint.url)) {
              const downloaded = await downloadDocument(
                api,
                hint,
                page,
                budget,
                controller.signal,
                captureId,
                pageSince,
                options.reusableDownloads,
                (url) => permittedTabs([{ ...current, url, finalUrl: url }]).length > 0,
              );
              if (downloaded && !controller.signal.aborted) accept(downloaded);
              return false;
            }
            const file = await fetchDocument(
              hint,
              page,
              budget,
              controller.signal,
              options.fetcher,
              (url) => permittedTabs([{ ...current, url, finalUrl: url }]).length > 0,
            );
            if (file && !controller.signal.aborted) accept(file.page, file);
          } catch (error) {
            if (
              !controller.signal.aborted &&
              error instanceof DocumentAccessError &&
              normalizeUrl(resolveDocumentUrl(page.url) ?? "") === normalizeUrl(hint.url)
            ) {
              updated.set(tab.tabId, {
                ...tab,
                access: error.access,
                summary,
                selection: undefined,
                position: undefined,
              });
              for (let index = tabPages.length - 1; index >= 0; index--)
                if (tabPages[index]!.tabId === tab.tabId) tabPages.splice(index, 1);
              tabSkipped.push({ tabId: tab.tabId, reason: error.access });
              return true;
            }
            if (!controller.signal.aborted)
              tabSkipped.push({
                tabId: tab.tabId,
                reason: readFailureReason(error),
              });
          }
          return false;
        };
        // The tab's original gets its full tab deadline before frame/link discovery.
        const primary = selectDocuments([], page.url)[0];
        if (primary && (await captureDocument(primary))) return;
        let hints: ReturnType<typeof discoverLinks> = [];
        try {
          const found = await within(
            api.scripting.executeScript({
              target: { tabId: tab.tabId, allFrames: true },
              func: discoverLinks,
            }),
            Math.max(0, Math.min(500, tabDeadline - Date.now())),
          );
          hints = found.flatMap((frame) => frame.result ?? []);
        } catch {
          /* A built-in PDF viewer still has its tab URL. */
        }
        if (controller.signal.aborted) return;
        // Probe every frame before fetching: an LMS shell may hold a blob-backed PDF.js viewer.
        try {
          const viewers = await within(
            api.scripting.executeScript({
              target: { tabId: tab.tabId, allFrames: true },
              world: "MAIN",
              func: probePdfViewer,
            }),
            Math.max(0, Math.min(500, tabDeadline - Date.now())),
          );
          for (const frame of viewers) {
            if (controller.signal.aborted) break;
            const viewer = frame.result;
            if (
              !viewer ||
              !/^https?:/i.test(viewer.frameUrl) ||
              !permittedTabs([{ ...current, url: viewer.frameUrl, finalUrl: viewer.frameUrl }])
                .length
            )
              continue;
            if (
              frame.frameId === 0 &&
              (tabFiles.some((file) => file.page.file?.primary) ||
                tabPages.some((page) => page.download?.primary))
            )
              continue;
            if (!viewer.memory) {
              hints.push({
                url: viewer.url,
                name: viewer.name,
                rank: 0,
                explicit: true,
                originUrl: viewer.frameUrl,
                ...(frame.frameId === 0 && normalizeUrl(viewer.frameUrl) === normalizeUrl(page.url)
                  ? { primary: true }
                  : {}),
              });
              continue;
            }
            const key = `pdfjs:${tab.tabId}:${frame.frameId}:${viewer.frameUrl}`;
            if (budget.urls.has(key)) continue;
            budget.urls.add(key);
            const primary =
              frame.frameId === 0 && normalizeUrl(viewer.frameUrl) === normalizeUrl(page.url);
            if (!primary && budget.count >= 10) {
              tabSkipped.push({
                tabId: tab.tabId,
                reason: "Discovered-link limit reached (10 per tab)",
              });
              continue;
            }
            if (!primary) budget.count++;
            try {
              let bytes: Uint8Array<ArrayBuffer> | undefined;
              let offset = 0;
              const available = Math.min(MAX_SOURCE_UPLOAD_BYTES, MAX_CAPTURE_BYTES - budget.bytes);
              do {
                const chunks = await api.scripting.executeScript({
                  target: { tabId: tab.tabId, frameIds: [frame.frameId] },
                  world: "MAIN",
                  func: readPdfChunk,
                  args: [offset, available, viewer.frameUrl],
                });
                if (controller.signal.aborted) break;
                const chunk = chunks[0]?.result;
                if (
                  !chunk ||
                  !Number.isSafeInteger(chunk.size) ||
                  chunk.size <= 0 ||
                  chunk.size > available
                )
                  throw new Error("Capture file limit exceeded");
                if (!bytes) {
                  if (budget.bytes + chunk.size > MAX_CAPTURE_BYTES)
                    throw new Error("Capture file limit exceeded");
                  bytes = new Uint8Array(chunk.size);
                  budget.bytes += chunk.size; // Reserve against other tab workers before the next await.
                }
                const data = Uint8Array.from(atob(chunk.data), (char) => char.charCodeAt(0));
                if (
                  chunk.size !== bytes.length ||
                  !data.length ||
                  offset + data.length > bytes.length
                )
                  throw new Error("Invalid PDF chunk");
                bytes.set(data, offset);
                offset += data.length;
              } while (offset < bytes!.length);
              if (!bytes || controller.signal.aborted) continue;
              let fileName = safeFileName(viewer.name) || "document.pdf";
              if (!/\.pdf$/i.test(fileName)) fileName += ".pdf";
              const pdf: PageSnapshot = {
                ...page,
                url: viewer.frameUrl,
                canonicalUrl: viewer.frameUrl,
                title: fileName,
                text: "",
                textLength: 0,
                file: {
                  url: viewer.frameUrl,
                  ...(primary ? { primary: true } : {}),
                  originUrl: viewer.frameUrl,
                  fileName,
                  mimeType: "application/pdf",
                  sizeBytes: bytes.length,
                  sha256: await sha256(bytes),
                },
              };
              if (!controller.signal.aborted) accept(pdf, { page: pdf, bytes });
            } catch {
              if (!controller.signal.aborted)
                tabSkipped.push({
                  tabId: tab.tabId,
                  reason: "PDF viewer document could not be read",
                });
            }
          }
        } catch {
          /* Restricted frames still leave link and timing discovery available. */
        }
        if (controller.signal.aborted) return;
        const documents = selectDocuments(hints, page.url, Infinity);
        if (
          /^https:\/\/drive\.google\.com\/(?:drive\/(?:u\/\d+\/)?)?folders\//.test(page.url) &&
          !documents.length
        )
          tabSkipped.push({
            tabId: tab.tabId,
            reason:
              "No downloadable files were found in this Drive folder. Open a file and capture again.",
          });
        for (const hint of documents) {
          if (controller.signal.aborted) break;
          if (await captureDocument(hint)) return;
        }
      };
      try {
        await within(read(), remaining);
      } catch (error) {
        tabSkipped.push({
          tabId: tab.tabId,
          reason: controller.signal.aborted
            ? "Read in browser timed out"
            : readFailureReason(error),
        });
      } finally {
        controller.abort();
        clearTimeout(timer);
      }
      if (Date.now() >= tabDeadline && !tabSkipped.some((item) => /timed out/i.test(item.reason)))
        tabSkipped.push({ tabId: tab.tabId, reason: "Read in browser timed out" });
      // A document tab's editor/viewer shell is not a substitute for its original.
      if (
        resolveDocumentUrl(tab.finalUrl ?? tab.url) &&
        !tabFiles.some((file) => file.page.file?.primary) &&
        !tabPages.some((page) => page.download?.primary)
      ) {
        for (let index = tabPages.length - 1; index >= 0; index--)
          if (!tabPages[index]!.file) tabPages.splice(index, 1);
      }
      pages.push(...tabPages);
      if (options.retainFiles !== false) files.push(...tabFiles);
      skipped.push(...tabSkipped);
      deliver({
        tabs: [publicTab(updated.get(tab.tabId)!)],
        pages: tabPages,
        files: tabFiles,
        skipped: tabSkipped.slice(0, 200),
      });
    }
  };
  try {
    await Promise.all(Array.from({ length: Math.min(6, tabs.length) }, worker));
    await Promise.all(deliveries);
  } finally {
    await restoreDownloads?.();
  }
  if (deliveryErrors.length) throw deliveryErrors[0];
  for (const tab of tabs.slice(next))
    skipped.push({ tabId: tab.tabId, reason: "Read in browser timed out" });
  return {
    tabs: [...updated.values()].map(publicTab),
    pages,
    files,
    skipped: skipped.slice(0, 200),
  };
}

export function captureResult(
  requestId: string,
  output: CaptureOutput,
  final = true,
): ExtensionMessage {
  return {
    _tag: "CaptureResult",
    final,
    version: 1,
    requestId,
    pages: output.pages,
    skipped: output.skipped,
  };
}
