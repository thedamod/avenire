import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";

/** Parse the flat theme declarations; dark inherits all light defaults. */
export function parseThemeTokens(css: string) {
  const block = (selector: string): Record<string, string> => {
    const body = new RegExp(`${selector}\\s*\\{([^}]+)\\}`).exec(css)?.[1];
    if (!body) throw new Error(`Missing theme block: ${selector}`);
    return Object.fromEntries(
      [...body.replace(/\/\*[\s\S]*?\*\//g, "").matchAll(/(--[a-z0-9-]+)\s*:\s*([^;]+);/g)].map(
        ([, name, value]) => [name!, value!.trim()],
      ),
    );
  };
  const light = block(":root");
  return { light, dark: { ...light, ...block("\\.dark") } };
}

export function widgetTokenSheet(names: ReadonlyArray<string>): string {
  const purposes: Record<string, string> = {
    background: "page surface",
    foreground: "body ink",
    card: "card surface",
    "card-foreground": "card ink",
    popover: "overlay surface",
    "popover-foreground": "overlay ink",
    primary: "main action",
    "primary-foreground": "main action ink",
    secondary: "secondary surface",
    "secondary-foreground": "secondary ink",
    muted: "subtle surface",
    "muted-foreground": "subtle ink",
    accent: "highlight surface",
    "accent-foreground": "highlight ink",
    destructive: "error or danger",
    border: "outlines",
    input: "input outlines",
    ring: "focus indicator",
    canvas: "drawing surface",
    "canvas-grid": "drawing grid",
    radius: "base corner radius",
  };
  const semantic = names.filter((name) => purposes[name.slice(2)]);
  return [
    "### Widget theme tokens",
    ...semantic.map((name) => `- ${name}: ${purposes[name.slice(2)]}.`),
    "- Fonts: --font-sans (body/UI), --font-serif (prose), --font-mono (code/numbers).",
    "- Type: --text-xs, --text-sm, --text-base, --text-lg, --text-xl, --text-2xl: increasing font sizes.",
    "- Leading: --leading-tight (headings), --leading-normal (body).",
    "- Space: --space-1, --space-2, --space-3, --space-4, --space-5, --space-6, --space-8: layout gaps/padding.",
    "- Charts: --chart-1, --chart-2, --chart-3, --chart-4, --chart-5, --chart-6: distinct series colours, in order.",
    "- Pair chart colours with labels or line patterns; colour alone must not carry meaning.",
    "- Use var(--…) for every colour, font, size and space; never hardcode colours.",
    "- Support light and dark: both come from the same variables.",
    "- Canvas: listen for `avenire:themechange` on window and re-read tokens with getComputedStyle(document.documentElement).",
  ].join("\n");
}

export function generateTokenSource(css: string): string {
  const tokens = parseThemeTokens(css);
  const names = Object.keys(tokens.light);
  return `// Generated by scripts/generate-tokens.ts. Do not edit.\n\nexport const THEME_TOKENS = ${JSON.stringify(tokens, null, 2)} as const;\n\nexport const THEME_TOKEN_NAMES: ReadonlyArray<string> = ${JSON.stringify(names, null, 2)};\n\nexport type ThemeTokens = Readonly<Record<string, string>>;\n\n/** Concise widget spec sheet listing each token with its purpose, for tool descriptions. */\nexport const WIDGET_TOKEN_SHEET: string = ${JSON.stringify(widgetTokenSheet(names))};\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const css = await readFile(new URL("../src/styles/globals.css", import.meta.url), "utf8");
  await writeFile(new URL("../src/styles/tokens.ts", import.meta.url), generateTokenSource(css));
}
