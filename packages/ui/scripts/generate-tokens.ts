import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";

/** Parse the flat theme declarations; dark inherits all light defaults. */
export function parseThemeTokens(css: string) {
  const block = (selector: string): Record<string, string> => {
    const body = new RegExp(`${selector}\\s*\\{([^}]+)\\}`).exec(css)?.[1];
    if (!body) throw new Error(`Missing theme block: ${selector}`);
    return Object.fromEntries(
      [...body.replace(/\/\*[\s\S]*?\*\//g, "").matchAll(/(--[a-z0-9-]+)\s*:\s*([^;]+);/g)].map(
        ([, name, value]) => [name!, value!.trim()],
      ),
    );
  };
  const light = block(":root");
  return { light, dark: { ...light, ...block("\\.dark") } };
}

export function widgetTokenSheet(names: ReadonlyArray<string>): string {
  const figures = names.filter((name) => name.startsWith("--figure-"));
  return [
    "### Widget figure tokens",
    "- Four-tone palette: " + figures.join(", ") + ".",
    "- Page/card/text/strong/muted: grounds and explanatory ink. Paper/face/top: opaque solid fills.",
    "- Shade-0..3: facing tones, darkest to lightest. Lit-top/lit-shade: the selected solid.",
    "- Hi/mid/lo/faint/lit: subject, structure, base, detail, one selected accent.",
    "- Halo plus halo-opacity: soft contact shadow. Dot: fasteners. Red/green/blue: signals only.",
    "- Weight: 0.6px hairlines; ease: cubic-bezier(.32,.72,0,1); mono: system stack; lift: subtle inset/drop shadow.",
    "- Frame: Fig n top left, mono uppercase title top right, hint bottom left, mono live readout bottom right; legend and true caption below.",
    "- --chart-1..6 are widget aliases for hi, mid, lo, red, green, blue. Pair colours with labels or patterns.",
    "- Widget semantic aliases (--background, --foreground, --card, --muted-foreground, --border etc.) use this palette; app UI retains its own colours.",
    "- Fonts: --font-sans (body), --font-serif (prose), --font-mono (technical labels).",
    "- Type: --text-xs/sm/base/lg/xl/2xl; --leading-tight/normal. Space: --space-1/2/3/4/5/6/8.",
    "- Use var(--…) for colours; --stroke-hairline and --figure-frame/label/leader follow the figure layer.",
    "- Host injects tokens before paint and updates .iso data-theme on theme messages; standalone --light builds still work.",
    "- Canvas: listen for avenire:themechange and re-read computed tokens from its themed .iso element.",
  ].join("\n");
}

export function widgetThemeTokens(tokens: Record<string, string>): Record<string, string> {
  const t = (name: string) => tokens[`--figure-${name}`]!;
  return {
    ...tokens,
    "--background": t("page"),
    "--foreground": t("text"),
    "--card": t("card"),
    "--card-foreground": t("strong"),
    "--popover": t("card"),
    "--popover-foreground": t("strong"),
    "--primary": t("lit"),
    "--primary-foreground": t("card"),
    "--secondary": t("shade-2"),
    "--secondary-foreground": t("strong"),
    "--muted": t("shade-3"),
    "--muted-foreground": t("muted"),
    "--accent": t("lit-shade"),
    "--accent-foreground": t("lit"),
    "--destructive": t("red"),
    "--border": t("mid"),
    "--input": t("lo"),
    "--ring": t("hi"),
    "--canvas": t("paper"),
    "--canvas-grid": t("faint"),
    "--radius": "0px",
    "--font-mono": t("mono"),
    "--stroke-hairline": t("weight"),
    "--figure-label": t("muted"),
    "--figure-leader": t("lo"),
    "--figure-frame": t("mid"),
    ...Object.fromEntries(
      ["hi", "mid", "lo", "red", "green", "blue"].map((tone, i) => [`--chart-${i + 1}`, t(tone)]),
    ),
  };
}

export function generateTokenSource(css: string): string {
  const tokens = parseThemeTokens(css);
  const names = Object.keys(tokens.light);
  const widgets = { light: widgetThemeTokens(tokens.light), dark: widgetThemeTokens(tokens.dark) };
  return `// Generated by scripts/generate-tokens.ts. Do not edit.\n\nexport const THEME_TOKENS = ${JSON.stringify(tokens, null, 2)} as const;\n\nexport const WIDGET_THEME_TOKENS = ${JSON.stringify(widgets, null, 2)} as const;\n\nexport const THEME_TOKEN_NAMES: ReadonlyArray<string> = ${JSON.stringify(names, null, 2)};\n\nexport type ThemeTokens = Readonly<Record<string, string>>;\n\n/** Concise widget spec sheet listing each token with its purpose, for tool descriptions. */\nexport const WIDGET_TOKEN_SHEET: string = ${JSON.stringify(widgetTokenSheet(names))};\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const css = await readFile(new URL("../src/styles/globals.css", import.meta.url), "utf8");
  await writeFile(new URL("../src/styles/tokens.ts", import.meta.url), generateTokenSource(css));
}
